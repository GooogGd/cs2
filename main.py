class Picker:
    """Выбирает элемент, избегая недавно использованных."""

    def __init__(self, items, memory_ratio=0.6):
        self.items = list(items)
        size = max(1, int(len(self.items) * memory_ratio))
        self.recent = deque(maxlen=size)

    def get(self):
        choice = random.choice(self.items)
        for _ in range(60):
            if choice not in self.recent:
                break
            choice = random.choice(self.items)
        self.recent.append(choice)
        return choice


KILL_PICKER = Picker(KILL_DETAILS, 0.7)
SPRAY_PICKER = Picker(KILL_SPRAY, 0.6)
AWP_PICKER = Picker(KILL_AWP, 0.6)
FAIL_PICKER = Picker(FAIL_DETAILS, 0.7)
FAIL_T_PICKER = Picker(FAIL_DETAILS_T, 0.5)
FAIL_CT_PICKER = Picker(FAIL_DETAILS_CT, 0.5)
CHAT_PICKER = Picker(CHAT_PHRASES, 0.8)


def pick_kill_detail(weapon_class):
    if weapon_class == "awp" and random.random() < 0.5:
        return AWP_PICKER.get()
    if weapon_class in ("rifle", "smg") and random.random() < 0.3:
        return SPRAY_PICKER.get()
    return KILL_PICKER.get()


def pick_fail_detail(side):
    roll = random.random()
    if roll < 0.15:
        return (FAIL_T_PICKER if side == "T" else FAIL_CT_PICKER).get()
    return FAIL_PICKER.get()


def pick_weapon(round_type, side):
    return random.choice(WEAPONS[round_type][side])


