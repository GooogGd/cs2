_MD_SPECIAL = re.compile(r'([_*\[\]()~`>#+\-=|{}.!\\])')


def esc(text):
    """Экранирует спецсимволы MarkdownV2."""
    return _MD_SPECIAL.sub(r'\\\1', str(text))


def bold(text):
    return "*" + esc(text) + "*"


def ital(text):
    return "_" + esc(text) + "_"


