def play_round(global_round):
    """Проигрывает один раунд.
    Возвращает (заголовок_раунда, список_событий, итог_раунда, сторона_победителя).
    Каждый элемент потом отправляется отдельным сообщением."""
    round_type = pick_round_type()

    # каждый раунд - свежее лобби из 10 случайных игроков
    lobby = random.sample(NICKNAMES, 10)
    alive = {"T": lobby[:5], "CT": lobby[5:]}
    kills_by_side = {"T": 0, "CT": 0}
    event_blocks = []
    eliminated_side = None  # сторона, которая выиграла полным уничтожением

    for _ in range(random.randint(3, 5)):
        if random.random() < KILL_EVENT_CHANCE:
            ks = random.choices(["T", "CT"], weights=[len(alive["T"]), len(alive["CT"])])[0]
            vs = "CT" if ks == "T" else "T"
            killer = random.choice(alive[ks])
            victim = random.choice(alive[vs])
            alive[vs].remove(victim)
            kills_by_side[ks] += 1
            weapon, wclass = pick_weapon(round_type, ks)
            detail = pick_kill_detail(wclass)
            event_blocks.append(
                "💀 " + SIDE_EMOJI[ks] + " " + bold(killer) + " 🔫 " + ital(weapon)
                + " ➜ " + SIDE_EMOJI[vs] + " " + bold(victim) + "\n└ " + esc(detail)
            )
            if not alive[vs]:
                eliminated_side = ks
                break
        else:
            fs = random.choice(["T", "CT"])
            player = random.choice(alive[fs])
            weapon, _wc = pick_weapon(round_type, fs)
            detail = pick_fail_detail(fs)
            event_blocks.append(
                "🤡 " + SIDE_EMOJI[fs] + " " + bold(player) + " " + esc("(") + ital(weapon) + esc(")")
                + "\n└ " + esc(detail)
            )

    # редкий чат: 0.5% за раунд
    if random.random() < CHAT_CHANCE:
        speaker = random.choice(lobby)
        event_blocks.append(
            "💬 " + esc("[ALL] ") + bold(speaker) + esc(": ") + ital(CHAT_PICKER.get())
        )

    # кто выиграл раунд
    if eliminated_side:
        winner_side = eliminated_side
        result_text = random.choice(ELIMINATION_TEXTS[winner_side])
    else:
        if kills_by_side["T"] > kills_by_side["CT"]:
            winner_side = "T"
        elif kills_by_side["CT"] > kills_by_side["T"]:
            winner_side = "CT"
        else:
            winner_side = random.choice(["T", "CT"])
        result_text = random.choice(BOMB_TEXTS[winner_side])

    header = "🏁 " + bold("Раунд №" + str(global_round)) + "\n" + esc(ROUND_TYPE_LABEL[round_type])
    return header, event_blocks, esc(result_text), winner_side


