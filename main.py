def load_state():
    if os.path.exists(STATE_FILE):
        try:
            with open(STATE_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
            return (
                int(data.get("global_round", 0)),
                int(data.get("t_score", 0)),
                int(data.get("ct_score", 0)),
            )
        except Exception:
            pass
    return 0, 0, 0


def save_state(global_round, t_score, ct_score):
    try:
        with open(STATE_FILE, "w", encoding="utf-8") as f:
            json.dump(
                {"global_round": global_round, "t_score": t_score, "ct_score": ct_score}, f
            )
    except Exception as e:
        print("[state] не удалось сохранить состояние:", e)


bot = telebot.TeleBot(BOT_TOKEN, parse_mode=None)


def send(text):
    """Отправка с обработкой лимитов Telegram и сетевых ошибок."""
    attempts = 0
    while attempts < 6:
        try:
            bot.send_message(
                CHANNEL_ID, text,
                parse_mode="MarkdownV2",
                disable_web_page_preview=True,
            )
            return True
        except ApiTelegramException as e:
            if e.error_code == 429:
                retry_after = 30
                try:
                    retry_after = int(e.result_json.get("parameters", {}).get("retry_after", 30))
                except Exception:
                    pass
                print("[telegram] лимит, ждём", retry_after, "сек")
                time.sleep(retry_after + 1)
            else:
                print("[telegram] ошибка API:", e)
                return False
        except Exception as e:
            attempts += 1
            print("[network] ошибка, повтор через 10 сек:", e)
            time.sleep(10)
    return False


